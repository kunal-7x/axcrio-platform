#!/usr/bin/env node
/**
 * Bundle every contract schema into a single JSON the `@growth-os/events` validator imports
 * at runtime (so the package is self-contained — it does NOT read the /contracts dir from
 * disk in a deployed service). Generated; regenerate alongside `codegen:types`.
 *
 *   node tools/codegen/bundle-schemas.mjs
 *
 * Output: packages/events/src/generated/schemas.bundle.json
 *   { schemas: { "<$id>": <schema> }, byType: { "<event_type>": "<$id>" }, generatedAt }
 */

import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildIndex, SCHEMAS_DIR, REPO_ROOT } from './lib.mjs';

const OUT = join(REPO_ROOT, 'packages', 'events', 'src', 'generated', 'schemas.bundle.json');

function main() {
  const index = buildIndex();
  const schemas = {};
  const byType = {};
  for (const s of index.schemas) {
    const json = JSON.parse(readFileSync(join(SCHEMAS_DIR, s.name + '.schema.json'), 'utf8'));
    if (!json.$id) throw new Error(`${s.name}: missing $id`);
    schemas[json.$id] = json;
    if (s.kind === 'event' && s.event_type) byType[s.event_type] = json.$id;
  }
  const bundle = {
    note: 'AUTO-GENERATED by tools/codegen/bundle-schemas.mjs. DO NOT EDIT. Source: contracts/schemas/.',
    envelopeId: 'https://contracts.growth-os.dev/schemas/event-envelope.schema.json',
    schemas,
    byType,
    count: Object.keys(schemas).length,
  };
  mkdirSync(join(REPO_ROOT, 'packages', 'events', 'src', 'generated'), { recursive: true });
  writeFileSync(OUT, JSON.stringify(bundle, null, 2) + '\n', 'utf8');
  console.log(`[bundle] wrote ${bundle.count} schemas + ${Object.keys(byType).length} type mappings -> ${OUT}`);
}

main();
